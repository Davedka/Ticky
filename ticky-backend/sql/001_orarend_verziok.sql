create table if not exists public.importok (
    id               bigint generated by default as identity primary key,

    verzio_id        bigint null references public.orarend_verziok(id) on delete cascade,

    fajlnev          text not null,
    fajl_meret       bigint not null default 0,
    fajl_sha256      text not null default '',
    formatum         text not null default 'ismeretlen',

    statusz          text not null default 'feldolgozva'
                     check (statusz in ('feldolgozva', 'ervenytelen', 'publikalva')),

    sorok_szama      integer not null default 0,
    hibak_szama      integer not null default 0,
    figyelmeztetesek_szama integer not null default 0,

    hibak            jsonb not null default '[]'::jsonb,
    figyelmeztetesek jsonb not null default '[]'::jsonb,
    statisztika      jsonb not null default '{}'::jsonb,

    letrehozta       uuid null,
    created_at       timestamptz not null default now()
);

create index if not exists importok_created_idx on public.importok (created_at desc);
create index if not exists importok_verzio_idx  on public.importok (verzio_id);

