create table if not exists public.orarend_verziok (
    id           bigint generated by default as identity primary key,

    nev          text not null,
    tanev        text not null,
    megjegyzes   text null,

    statusz      text not null default 'draft'
                 check (statusz in ('draft', 'active', 'archived')),

    letrehozta   uuid null,
    created_at   timestamptz not null default now(),
    published_at timestamptz null
);

-- Egy időben legfeljebb EGY aktív órarend lehet. Ezt adatbázis szinten
-- kényszerítjük ki, hogy programhiba se tudjon két aktív verziót előállítani.
create unique index if not exists orarend_verziok_egy_aktiv
    on public.orarend_verziok (statusz)
    where statusz = 'active';

create index if not exists orarend_verziok_statusz_idx
    on public.orarend_verziok (statusz, created_at desc);

-- ─────────────────────────────────────────────────────────────────
-- 2. Import napló
