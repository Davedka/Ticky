// Visszaadja, mely csoportok vannak jelen az adott sávban, HA nem mind.
// Üres tömb = teljes osztály (vagy normál bontás) → nincs külön címke.
function ticky_reszleges_csoportok(string $class, int $day, string $start): array {
    $map   = ticky_csoport_partial_map();
    $start = substr($start, 0, 5);
    return array_values(array_map('intval', $map[$class][$day][$start] ?? []));
}

// Visszaadja, hogy az adott (osztály, nap, óra-kezdés, tanár-rövid-név) kombi
// melyik csoportokra vonatkozik. Ha üres tömb, akkor nem tudjuk azonosítani.
function ticky_csoport_szam_tanarbol(string $class, int $day, string $start, string $teacher_short): array {
    $map   = ticky_csoport_teacher_groups();
    $start = substr($start, 0, 5);
    $teacher_short = trim($teacher_short);
    $slot = $map[$class][$day][$start] ?? [];
    if (!isset($slot[$teacher_short])) {
        return [];
    }
    return array_values(array_map('intval', $slot[$teacher_short]));
}

// Emberi címke: "csak a 2. csoport" / "csak az 1. csoport".
function ticky_reszleges_szoveg(array $groups): string {
    if ($groups === []) {
        return '';
    }
    if (count($groups) === 1) {
        $n   = (int) $groups[0];
        $art = in_array($n, [1, 5], true) ? 'az' : 'a';
        return 'csak ' . $art . ' ' . $n . '. csoport';
    }
    $parts = array_map(static fn($n) => (int) $n . '.', $groups);
    return 'csak a ' . implode(' és ', $parts) . ' csoport';
}

// Címke a hiányzó csoportokra (pl. "az 1. csoportnak nincs órája").
function ticky_hianyzo_csoport_szoveg(array $present, int $max_groups = 2): string {
    if ($present === []) {
        return '';
    }
    $hianyzo = [];
    for ($g = 1; $g <= $max_groups; $g++) {
        if (!in_array($g, $present, true)) {
            $hianyzo[] = $g;
        }
    }
    if ($hianyzo === []) {
        return '';
    }
    if (count($hianyzo) === 1) {
        $n   = (int) $hianyzo[0];
        $art = in_array($n, [1, 5], true) ? 'az' : 'a';
        return $art . ' ' . $n . '. csoportnak nincs órája';
    }
    $parts = array_map(static fn($n) => (int) $n . '.', $hianyzo);
    return 'a ' . implode(' és ', $parts) . ' csoportnak nincs órája';
}
